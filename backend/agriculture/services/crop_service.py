from pathlib import Path

import joblib
import numpy as np
from django.conf import settings
from agriculture.models import RecommendationHistory
from rest_framework import status
from rest_framework.response import Response


MODEL_PATH = (
    Path(settings.BASE_DIR)
    / "agriculture"
    / "ml_models"
    / "crop_recommender.joblib"
)

REQUIRED_FIELDS = [
    "nitrogen",
    "phosphorus",
    "potassium",
    "temperature",
    "humidity",
    "ph",
    "rainfall",
]

# Preliminary input sanity limits; refine for supported regions and units.
FIELD_BOUNDS = {
    "nitrogen": (0, 300),
    "phosphorus": (0, 300),
    "potassium": (0, 300),
    "temperature": (-10, 60),
    "humidity": (0, 100),
    "ph": (0, 14),
    "rainfall": (0, 5000),
}

ARTIFACT = joblib.load(MODEL_PATH)
MODEL = ARTIFACT["model"]
FEATURES = ARTIFACT["features"]
TEST_ACCURACY = float(ARTIFACT["test_accuracy"])


def recommend_crop(request):
    data = request.data
    errors = {}
    values = {}

    for field in REQUIRED_FIELDS:
        if field not in data:
            errors[field] = "This field is required."
            continue

        try:
            value = float(data[field])
        except (TypeError, ValueError):
            errors[field] = "Must be a valid number."
            continue

        if not np.isfinite(value):
            errors[field] = "Value must be finite."
            continue

        minimum, maximum = FIELD_BOUNDS[field]
        if not minimum <= value <= maximum:
            errors[field] = (
                f"Value must be between {minimum} and {maximum}."
            )
            continue

        values[field] = value

    if errors:
        return Response(
            {"error": "Invalid input", "fields": errors},
            status=status.HTTP_400_BAD_REQUEST,
        )

    features = np.array(
        [[values[field] for field in FEATURES]],
        dtype=float,
    )

    prediction = str(MODEL.predict(features)[0])
    probabilities = MODEL.predict_proba(features)[0]
    confidence = float(np.max(probabilities))

    result = {
        "status": "success",
        "message": "Crop prediction generated by the trained model.",
        "input": values,
        "prediction": {
            "crop": prediction,
            "confidence": round(confidence, 4),
            "confidence_percent": round(confidence * 100, 2),
        },
        "model_evaluation": {
            "held_out_test_accuracy": round(TEST_ACCURACY, 4),
            "held_out_test_accuracy_percent": round(TEST_ACCURACY * 100, 2),
            "dataset_rows": ARTIFACT["dataset_rows_used"],
            "training_rows": ARTIFACT["training_rows"],
            "test_rows": ARTIFACT["test_rows"],
            "dataset_source": ARTIFACT["dataset_source"],
        },
        "limitations": [
            "Test accuracy is measured on a held-out split of the training dataset.",
            "Prediction confidence is not a guarantee of real-world suitability.",
            "Verify recommendations against local soil tests, season, region, water availability, and agricultural guidance.",
            "Input bounds are preliminary sanity checks, not crop-specific suitability rules.",
        ],
    }

    # History is private to the authenticated user.
    # A history-write failure should not discard a valid crop prediction.
    try:
        RecommendationHistory.objects.create(
            user=request.user,
            recommendation_type="crop",
            inputs=values,
            result=result,
        )
    except Exception:
        import logging
        logging.getLogger(__name__).exception(
            "Could not save crop recommendation history."
        )

    return Response(result, status=status.HTTP_200_OK)
